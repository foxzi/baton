// The generated pack must load through packs.Parse: that is the contract
// that matters, not the exact YAML text.
func TestApisImportOutputLoadsThroughPacksParse(t *testing.T) {
	path := writeSpec(t, demoSpec)

	var code int
	stdout, _ := captureOutput(t, func() {
		code = apisCmd([]string{"import", "--openapi", path, "--ops", "getThing"})
	})
	if code != exitcode.OK {
		t.Fatalf("exit code = %d, want %d", code, exitcode.OK)
	}
	if _, err := packs.Parse([]byte(stdout), "generated.yaml"); err != nil {
		t.Fatalf("packs.Parse: %v\n--- generated ---\n%s", err, stdout)
	}
}
